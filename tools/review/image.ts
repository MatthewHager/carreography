const GLYPHS = new Map<string, string[]>(FONT.split('\n').filter((l) => l.length > 2)
  .map((l) => [l[0], l.slice(2).split(' ')]));
const SAME: Record<string, string> = { '→': '>', '′': "'", '×': 'x', '–': '-', '—': '-' };

const CHAR_W = 6;                  // a glyph and the gap after it

export class Picture {
  readonly px: Uint8Array;

  constructor(readonly w: number, readonly h: number, bg: Rgb = [0, 0, 0]) {
    this.px = new Uint8Array(w * h * 3);
    this.rect(0, 0, w, h, bg);
  }

  set(x: number, y: number, c: Rgb): void {
    x = Math.round(x);
    y = Math.round(y);
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const i = (y * this.w + x) * 3;
    this.px[i] = c[0];
    this.px[i + 1] = c[1];
    this.px[i + 2] = c[2];
  }

  rect(x: number, y: number, w: number, h: number, c: Rgb): void {
    const x0 = Math.max(0, Math.round(x)), x1 = Math.min(this.w, Math.round(x + w));
    const y0 = Math.max(0, Math.round(y)), y1 = Math.min(this.h, Math.round(y + h));
    for (let yy = y0; yy < y1; yy++) for (let xx = x0; xx < x1; xx++) this.set(xx, yy, c);
  }

  /** Text with its top left at (x, y), cut off at maxW pixels. */
  text(x: number, y: number, s: string, c: Rgb, maxW = Infinity): void {
    const n = Math.min(s.length, Math.floor(maxW / CHAR_W));
    for (let k = 0; k < n; k++) {
      const ch = SAME[s[k]] ?? s[k];
      const g = GLYPHS.get(ch) ?? GLYPHS.get('?')!;
      for (let r = 0; r < 8; r++) {
        for (let q = 0; q < 5; q++) if (g[r][q] === '#') this.set(x + k * CHAR_W + q, y + r, c);
      }
    }
  }

  /** The picture as a PNG file (8-bit RGB). */
  png(): Buffer {
    const raw = Buffer.alloc((this.w * 3 + 1) * this.h);
    for (let y = 0; y < this.h; y++) {
      raw[y * (this.w * 3 + 1)] = 0;
      raw.set(this.px.subarray(y * this.w * 3, (y + 1) * this.w * 3), y * (this.w * 3 + 1) + 1);
    }
    const chunk = (type: string, data: Buffer) => {
      const head = Buffer.alloc(8);
      head.writeUInt32BE(data.length, 0);
      head.write(type, 4, 'latin1');
      const crc = Buffer.alloc(4);
      crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])) >>> 0, 0);
      return Buffer.concat([head, data, crc]);
    };
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(this.w, 0);
    ihdr.writeUInt32BE(this.h, 4);
    ihdr.set([8, 2, 0, 0, 0], 8);
    return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr),
      chunk('IDAT', deflateSync(raw, { level: 6 })), chunk('IEND', Buffer.alloc(0))]);
  }
}

/** c scaled by level (0..1); anything lit at all shows at least a glimmer. */
export function dim(c: Rgb, level: number): Rgb {
  const k = level <= 0.01 ? 0 : 0.18 + 0.82 * Math.min(1, level);
  return [Math.round(c[0] * k), Math.round(c[1] * k), Math.round(c[2] * k)];
}

export function mix(a: Rgb, b: Rgb, t: number): Rgb {
  const at = (k: number) => Math.round(a[k] + (b[k] - a[k]) * t);
  return [at(0), at(1), at(2)];
}
